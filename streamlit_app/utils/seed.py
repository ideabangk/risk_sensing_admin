def seed_companies():
    from utils.db import get_supabase
    sb = get_supabase()
    existing = {r["name"] for r in sb.table("companies").select("name").execute().data}
    inserted = 0
    for name, keywords in COMPANIES:
        if name not in existing:
            sb.table("companies").insert({
                "name": name,
                "search_keywords": keywords,
                "is_active": True,
            }).execute()
            inserted += 1
    return inserted
